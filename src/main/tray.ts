/** Menu-bar / tray icon with a mini view of unread counts and recent notifications (FR-X25). */
import { join } from 'node:path';
import { app as electronApp, BrowserWindow, Menu, nativeImage, screen, Tray } from 'electron';
import { loadRenderer, resource, type Extrovert } from './app';

const W = 340;
const H = 470;

export class TrayUI {
  private tray: Tray;
  private panel: BrowserWindow | null = null;

  constructor(private readonly app: Extrovert) {
    this.tray = new Tray(trayIcon(process.platform === 'darwin'));
    this.tray.setToolTip('Extrovert');
    this.tray.on('click', () => this.toggle());
    this.tray.on('right-click', () => this.tray.popUpContextMenu(this.menu()));
    // Most Linux desktops ignore tray clicks and only show a menu set in advance.
    if (process.platform === 'linux') this.tray.setContextMenu(this.menu());
  }

  private menu(): Menu {
    return Menu.buildFromTemplate([
      { label: 'Open Extrovert', click: () => this.app.showWindow() },
      ...(process.platform === 'linux' ? [{ label: 'Unread & notifications', click: () => this.toggle() }] : []),
      { label: 'Do Not Disturb', type: 'checkbox', checked: this.app.store.settings.dnd, click: (i) => {
        this.app.updateSettings({ dnd: i.checked });
        if (process.platform === 'linux') this.tray.setContextMenu(this.menu());
      } },
      { type: 'separator' },
      { role: 'quit' },
    ]);
  }

  webContents(): Electron.WebContents[] {
    return this.panel && !this.panel.isDestroyed() ? [this.panel.webContents] : [];
  }

  setUnread(total: number): void {
    if (process.platform === 'darwin') this.tray.setTitle(total ? String(total > 99 ? '99+' : total) : '');
    this.tray.setToolTip(total ? `Extrovert · ${total} unread` : 'Extrovert');
  }

  private toggle(): void {
    if (this.panel?.isVisible()) return this.panel.hide();
    this.panel ??= this.create();
    const b = this.tray.getBounds();
    const area = screen.getDisplayNearestPoint({ x: b.x, y: b.y }).workArea;
    const x = Math.min(Math.max(area.x + 8, Math.round(b.x + b.width / 2 - W / 2)), area.x + area.width - W - 8);
    const below = b.y < area.y + area.height / 2; // macOS menu bar at the top, Windows taskbar usually at the bottom
    this.panel.setBounds({ x, y: below ? b.y + b.height + 4 : b.y - H - 4, width: W, height: H });
    this.panel.show();
    this.panel.focus();
    this.panel.webContents.send('state', this.app.store.snapshot());
  }

  private create(): BrowserWindow {
    const win = new BrowserWindow({
      width: W, height: H, show: false, frame: false, resizable: false, movable: false, skipTaskbar: true,
      alwaysOnTop: true, fullscreenable: false, transparent: true, backgroundColor: '#00000000',
      webPreferences: { preload: join(__dirname, '../preload/shell.js'), sandbox: true, contextIsolation: true, devTools: !electronApp.isPackaged },
    });
    win.on('blur', () => win.hide());
    loadRenderer(win.webContents, 'tray');
    return win;
  }

  hide(): void {
    this.panel?.hide();
  }
}

/**
 * Logo A from resources/ (generated by `pnpm icons`). On macOS a one-color template image that the
 * system tints for light and dark menu bars; on Windows and Linux the full-color tile.
 */
function trayIcon(mac: boolean): Electron.NativeImage {
  const img = nativeImage.createFromPath(resource(mac ? 'trayTemplate.png' : 'tray.png'));
  if (mac) img.setTemplateImage(true);
  return img;
}
